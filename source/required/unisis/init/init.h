#if !defined INIT_H
#define INIT_H

#include "init_config.h"

/**
 * @brief 初始化极早期模块
 *
 * @details 这是最早执行的初始化函数标记宏.
 *          通常用于需要在系统启动极早期就完成的初始化操作,
 *          比如对一些硬件的最基础配置、早期内存管理相关的设置等.
 *          这些操作一般是后续其他初始化步骤的基础,必须在系统启动的最初阶段完成.
 * @example 1. 可能用于初始化早期的时钟源,确保系统在启动初期就有一个稳定的时钟基准.
 *          2. 对一些硬件寄存器进行早期的设置.
 */
#define early_initcall(func) __define_initcall(func, early)

/**
 * @brief 初始化纯粹模块
 *
 * @details 用于标记那些纯粹的初始化函数,
 *          这些函数不依赖于其他子系统的初始化结果,是非常基础的初始化操作.
 *          它们在系统启动过程中较早被调用,为后续的初始化工作提供基本的环境支持.
 * @example 初始化一些全局的数据结构,这些数据结构在后续的内核初始化和运行过程中会被广泛使用.
 */
#define pure_initcall(func) __define_initcall(func, 0)

/**
 * @brief 初始化内核核心子系统
 *
 * @details 主要用于内核核心子系统的初始化.
 *          内核的核心功能模块(如内存管理子系统)通常会使用这个级别的初始化函数.
 *          这些初始化操作对于系统的正常运行至关重要,是内核启动过程中的关键步骤.
 * @example 1. 初始化物理内存管理,包括内存页的分配和释放机制等,为后续内核和用户空间的内存使用提供基础.
 *          2. 初始化内核调度器的基本数据结构.
 */
#define core_initcall(func) __define_initcall(func, 1)

/**
 * @brief 初始化内核核心子系统初始化完成之后的模块
 *
 * @details 在核心子系统初始化完成之后执行的初始化操作.
 *          这些操作可能依赖于核心子系统的初始化结果,用于进一步完善内核的运行环境.
 * @example 1. 在内存管理子系统初始化完成后,对内核虚拟内存空间进行一些额外的配置和调整.
 *          2. 对内核的中断处理机制进行一些后期的优化设置.
 */
#define postcore_initcall(func) __define_initcall(func, 2)

/**
 * @brief 初始化特定架构相关
 *
 * @details 用于特定架构相关的初始化操作.
 *          不同的硬件架构(如 x86、ARM 等)可能有不同的硬件特性和要求,
 *          这个级别的初始化函数会针对具体的架构进行相应的配置和初始化.
 * @example 1. 在 ARM 架构上,初始化特定的协处理器或者配置架构相关的寄存器.
 *          2. 在 x86 架构上,设置中断描述符表(IDT).
 */
#define arch_initcall(func) __define_initcall(func, 3)

/**
 * @brief 初始化内核各个子系统
 *
 * @details 用于内核各个子系统的初始化.
 *          这里的子系统可以是文件系统、网络子系统等.
 *          这些子系统相对独立,但又需要在一定的环境基础上进行初始化,
 *          通常在核心和架构相关初始化完成之后执行.
 * @example 1. 初始化网络子系统的基础结构,为后续网络设备的驱动和网络协议的运行提供支持.
 *          2. 初始化块设备子系统,为文件系统的使用做准备.
 */
#define subsys_initcall(func) __define_initcall(func, 4)

/**
 * @brief 初始化文件系统
 *
 * @details 专门用于文件系统的初始化操作.
 *          文件系统是操作系统中非常重要的一部分,这个级别的初始化函数会对各种文件系统
 *          (如 ext4、XFS 等)进行注册和初始化,以便系统能够正常访问和管理文件.
 * @example 1. 注册 ext4 文件系统的驱动程序,初始化文件系统的元数据结构.
 *          2. 挂载根文件系统.
 */
#define fs_initcall(func) __define_initcall(func, 5)

/**
 * @brief 初始化设备驱动
 *
 * @details 用于设备驱动的初始化.
 *          在这个阶段,系统会对各种硬件设备进行探测和初始化,
 *          加载相应的设备驱动程序,使设备能够正常工作.
 * @example 1. 初始化 USB 设备驱动,检测连接的 USB 设备并进行配置.
 *          2. 初始化显卡驱动,设置显示模式.
 */
#define device_initcall(func) __define_initcall(func, 6)

/**
 * @brief 初始化系统启动过程中较晚执行的模块
 *
 * @details 这是系统启动过程中较晚执行的初始化操作.
 *          这些操作通常依赖于前面大部分初始化步骤的完成,用于完成一些最后的系统配置和收尾工作.
 * @example 1. 启动一些后台服务进程,如日志服务.
 *          2. 进行一些用户空间相关的初始化操作,为用户登录和应用程序的运行做准备.
 */
#define late_initcall(func) __define_initcall(func, 7)

#endif /* !defined INIT_H */
